using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._CorvaxGoob.Redspace;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._CorvaxGoob.Redspace.UI;

[GenerateTypedNameReferences]
public sealed partial class RedspaceGateWindow : FancyWindow
{
    public event Action<float, float>? OpenPortal;
    public event Action? ClosePortal;
    public event Action? EjectDisk;

    private RedspaceGateBoundUserInterfaceState? _state;
    private bool _prefilled;

    public RedspaceGateWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        OpenButton.OnPressed += _ => TrySubmit();
        ClosePortalButton.OnPressed += _ => ClosePortal?.Invoke();
        CloseWindowButton.OnPressed += _ => Close();
        EjectButton.OnPressed += _ => EjectDisk?.Invoke();
        UseGatePositionButton.OnPressed += _ =>
        {
            if (_state == null)
                return;
            XEdit.Text = _state.GatePosition.X.ToString("0.##", CultureInfo.InvariantCulture);
            YEdit.Text = _state.GatePosition.Y.ToString("0.##", CultureInfo.InvariantCulture);
        };
        XEdit.OnTextEntered += _ => TrySubmit();
        YEdit.OnTextEntered += _ => TrySubmit();
    }

    private static bool TryParse(string text, out float value)
    {
        text = text.Trim().Replace(',', '.');
        return float.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out value) && float.IsFinite(value);
    }

    private void TrySubmit()
    {
        if (!TryParse(XEdit.Text, out var x) || !TryParse(YEdit.Text, out var y))
        {
            StatusLabel.Text = Loc.GetString("redspace-gate-fail-invalid-coordinates");
            return;
        }

        OpenPortal?.Invoke(x, y);
    }

    public void UpdateState(RedspaceGateBoundUserInterfaceState state)
    {
        _state = state;

        StatusLabel.Text = Loc.GetString(state.Open ? "redspace-gate-window-status-open" : "redspace-gate-window-status-closed");
        MapLabel.Text = state.TargetMapName;
        DiskLabel.Text = !state.DiskInserted
            ? Loc.GetString("redspace-gate-window-disk-none")
            : !state.DiskValid
                ? Loc.GetString("redspace-gate-window-disk-invalid")
                : state.DiskTarget is { } diskTarget
                    ? Loc.GetString("redspace-gate-window-disk-coordinates",
                        ("x", diskTarget.X.ToString("0.##", CultureInfo.InvariantCulture)),
                        ("y", diskTarget.Y.ToString("0.##", CultureInfo.InvariantCulture)))
                    : Loc.GetString("redspace-gate-window-disk-ok");

        // A disk printed by ftldiskgate pins the coordinates: show them and lock the fields.
        var pinned = state.DiskTarget != null;
        if (state.DiskTarget is { } pinnedTarget)
        {
            XEdit.Text = pinnedTarget.X.ToString("0.##", CultureInfo.InvariantCulture);
            YEdit.Text = pinnedTarget.Y.ToString("0.##", CultureInfo.InvariantCulture);
            _prefilled = true;
        }
        XEdit.Editable = !pinned;
        YEdit.Editable = !pinned;
        UseGatePositionButton.Disabled = pinned;
        EjectButton.Disabled = !state.DiskInserted;
        GatePositionLabel.Text = $"{state.GatePosition.X:0.#}, {state.GatePosition.Y:0.#}";

        if (!_prefilled && state.Target is { } target)
        {
            XEdit.Text = target.X.ToString("0.##", CultureInfo.InvariantCulture);
            YEdit.Text = target.Y.ToString("0.##", CultureInfo.InvariantCulture);
            _prefilled = true;
        }

        BluespaceBar.Value = state.BluespaceCapacity > 0 ? (float) state.Bluespace / state.BluespaceCapacity : 0f;
        BluespaceCountLabel.Text = $"{state.Bluespace}/{state.BluespaceCapacity}";
        RedspaceBar.Value = state.RedspaceCapacity > 0 ? (float) state.Redspace / state.RedspaceCapacity : 0f;
        RedspaceCountLabel.Text = $"{state.Redspace}/{state.RedspaceCapacity}";
        BluespaceLabel.Text = Loc.GetString("redspace-gate-window-bluespace",
            ("count", state.Bluespace));
        RedspaceLabel.Text = Loc.GetString("redspace-gate-window-redspace",
            ("count", state.Redspace));

        OpenButton.Disabled = state.Open || state.Bluespace + state.Redspace <= 0 || !state.DiskValid;
        ClosePortalButton.Disabled = !state.Open;
    }
}

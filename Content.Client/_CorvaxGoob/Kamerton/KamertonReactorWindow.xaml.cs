using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._CorvaxGoob.Kamerton;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._CorvaxGoob.Kamerton;

[GenerateTypedNameReferences]
public sealed partial class KamertonReactorWindow : FancyWindow
{
    private static readonly Color Stable = Color.FromHex("#39C6FF");
    private static readonly Color Unstable = Color.FromHex("#E0304A");
    private static readonly Color Ok = Color.FromHex("#7FE07F");

    public event Action? Start;
    public event Action? Stop;
    public event Action? Scram;
    public event Action<KamertonDroneCommand>? DroneCommand;

    public KamertonReactorWindow()
    {
        RobustXamlLoader.Load(this);

        StartButton.OnPressed += _ => Start?.Invoke();
        StopButton.OnPressed += _ => Stop?.Invoke();
        ScramButton.OnPressed += _ => Scram?.Invoke();
        ScramButton.ModulateSelfOverride = Unstable;
        DroneLoadButton.OnPressed += _ => DroneCommand?.Invoke(KamertonDroneCommand.Load);
        DroneUnloadButton.OnPressed += _ => DroneCommand?.Invoke(KamertonDroneCommand.Unload);
        DroneReturnButton.OnPressed += _ => DroneCommand?.Invoke(KamertonDroneCommand.Return);
        DroneAutoCheck.OnPressed += _ => DroneCommand?.Invoke(KamertonDroneCommand.ToggleAuto);
    }

    private static string N(float value) => MathF.Round(value).ToString("0", CultureInfo.InvariantCulture);
    private static string Kw(float watts) => (watts / 1000f).ToString("0.#", CultureInfo.InvariantCulture);

    public void UpdateState(KamertonReactorBoundUserInterfaceState s)
    {
        ArraysBox.RemoveAllChildren();
        SinksBox.RemoveAllChildren();

        if (!s.Linked)
        {
            StatusLabel.Text = Loc.GetString("kamerton-reactor-window-unlinked");
            StatusLabel.FontColorOverride = Unstable;
            TempBar.Value = 0f;
            TempLabel.Text = "-";
            PowerBar.Value = 0f;
            PowerLabel.Text = "-";
            PairsLabel.Text = "-";
            OutputLabel.Text = "-";
            RingLabel.Text = "-";
            CoolingHeader.Text = Loc.GetString("kamerton-reactor-window-cooling", ("radiators", 0));
            HintLabel.Text = Loc.GetString("kamerton-reactor-window-hint-unlinked");
            StartButton.Disabled = true;
            StopButton.Disabled = true;
            ScramButton.Disabled = true;
            UpdateDrone(new KamertonDroneInfo());
            return;
        }

        StatusLabel.Text = Loc.GetString(s.Running ? "kamerton-reactor-window-running"
            : s.ScramCooldown > 0f ? "kamerton-reactor-window-scrammed"
            : s.Assembled ? "kamerton-reactor-window-stopped"
            : "kamerton-reactor-window-not-assembled", ("seconds", N(s.ScramCooldown)));
        StatusLabel.FontColorOverride = s.Running ? Ok : s.ScramCooldown > 0f ? Unstable : null;

        TempBar.Value = s.CollapseTemperature > 0f ? Math.Clamp(s.Temperature / s.CollapseTemperature, 0f, 1f) : 0f;
        TempLabel.Text = $"{N(s.Temperature)} / {N(s.CollapseTemperature)} K";
        TempLabel.FontColorOverride = s.Temperature > s.CollapseTemperature * 0.75f ? Unstable : null;

        PowerBar.Value = s.MaxPower > 0f ? Math.Clamp(s.TotalPower / s.MaxPower, 0f, 1f) : 0f;
        PowerLabel.Text = $"{Kw(s.TotalPower)} / {Kw(s.MaxPower)} kW";
        PairsLabel.Text = Loc.GetString("kamerton-reactor-window-pairs-value", ("pairs", s.ActivePairs), ("syncs", s.Synchronizers));
        OutputLabel.Text = s.PowerUnitLinked
            ? Loc.GetString("kamerton-reactor-window-output-value", ("kw", Kw(s.PowerSupplied)))
            : Loc.GetString("kamerton-reactor-window-output-none");

        RingLabel.Text = s.RingComplete
            ? Loc.GetString("kamerton-reactor-window-ring-ok")
            : Loc.GetString("kamerton-reactor-window-ring-broken", ("missing", s.RingMissing));
        RingLabel.FontColorOverride = s.RingComplete ? Ok : Unstable;

        foreach (var a in s.Arrays)
        {
            var label = new Label
            {
                Text = Loc.GetString(a.Stable ? "kamerton-reactor-window-array-stable" : "kamerton-reactor-window-array-unstable",
                    ("charged", a.Charged), ("empty", a.Empty), ("slots", a.Slots),
                    ("minutes", a.MinRemaining < 0f ? "-" : (a.MinRemaining / 60f).ToString("0.0", CultureInfo.InvariantCulture))),
                FontColorOverride = a.Stable ? Stable : Unstable,
            };
            ArraysBox.AddChild(label);
        }

        CoolingHeader.Text = Loc.GetString("kamerton-reactor-window-cooling", ("radiators", s.Radiators));
        var i = 1;
        foreach (var h in s.HeatSinks)
        {
            SinksBox.AddChild(new Label
            {
                Text = Loc.GetString("kamerton-reactor-window-sink", ("index", i++),
                    ("flow", h.FlowMoles.ToString("0.0", CultureInfo.InvariantCulture)),
                    ("tin", N(h.InletTemperature)), ("tout", N(h.OutletTemperature)), ("kw", Kw(h.HeatRemoved))),
            });
        }

        if (s.HeatSinks.Count == 0)
            SinksBox.AddChild(new Label { Text = Loc.GetString("kamerton-reactor-window-no-sinks") });

        HintLabel.Text = s.Temperature > s.CollapseTemperature * 0.75f
            ? Loc.GetString("kamerton-reactor-window-hint-hot")
            : !s.RingComplete && s.Running ? Loc.GetString("kamerton-reactor-window-hint-ring") : string.Empty;

        StartButton.Disabled = s.Running || !s.Assembled || s.ScramCooldown > 0f;
        StopButton.Disabled = !s.Running;
        ScramButton.Disabled = false;
        UpdateDrone(s.Drone);
    }

    private void UpdateDrone(KamertonDroneInfo d)
    {
        DroneStatusLabel.Text = !d.HasDrone
            ? Loc.GetString("kamerton-reactor-window-drone-none")
            : Loc.GetString(d.State switch
            {
                KamertonDroneState.Working => d.Task == KamertonDroneCommand.Unload
                    ? "kamerton-reactor-window-drone-unloading"
                    : "kamerton-reactor-window-drone-loading",
                KamertonDroneState.Returning => "kamerton-reactor-window-drone-returning",
                _ => "kamerton-reactor-window-drone-idle",
            });
        DroneStatusLabel.FontColorOverride = !d.HasDrone ? Unstable : d.State == KamertonDroneState.Working ? Ok : null;

        StorageLabel.Text = d.HasStorage
            ? Loc.GetString("kamerton-reactor-window-storage-value", ("stable", d.StorageStable),
                ("unstable", d.StorageUnstable), ("capacity", d.StorageCapacity))
            : Loc.GetString("kamerton-reactor-window-storage-none");
        StorageLabel.FontColorOverride = d.HasStorage ? null : Unstable;
        SlotsLabel.Text = Loc.GetString("kamerton-reactor-window-slots-value", ("stable", d.FreeStable),
            ("unstable", d.FreeUnstable), ("spent", d.Spent));

        var usable = d.HasDrone && d.HasStorage;
        DroneLoadButton.Disabled = !usable;
        DroneUnloadButton.Disabled = !usable;
        DroneReturnButton.Disabled = !d.HasDrone;
        DroneAutoCheck.Disabled = !d.HasDrone;
        DroneAutoCheck.Pressed = d.AutoRefuel;
    }
}

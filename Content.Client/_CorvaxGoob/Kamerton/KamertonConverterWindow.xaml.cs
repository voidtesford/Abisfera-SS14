using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._CorvaxGoob.Kamerton;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._CorvaxGoob.Kamerton;

[GenerateTypedNameReferences]
public sealed partial class KamertonConverterWindow : FancyWindow
{
    public event Action? Start;
    public event Action? Charge;
    public event Action? Print;
    public event Action? Eject;

    public KamertonConverterWindow()
    {
        RobustXamlLoader.Load(this);

        StartButton.OnPressed += _ => Start?.Invoke();
        ChargeButton.OnPressed += _ => Charge?.Invoke();
        PrintButton.OnPressed += _ => Print?.Invoke();
        EjectButton.OnPressed += _ => Eject?.Invoke();
    }

    private static string N(float value) => MathF.Floor(value).ToString("0", CultureInfo.InvariantCulture);

    public void UpdateState(KamertonConverterBoundUserInterfaceState s)
    {
        var create = s.Mode == KamertonConverterMode.Create;
        ModeLabel.Text = Loc.GetString(create ? "kamerton-converter-window-mode-create" : "kamerton-converter-window-mode-destroy");
        ModeLabel.FontColorOverride = create ? Color.FromHex("#39C6FF") : Color.FromHex("#E0304A");
        WorkLabel.Text = Loc.GetString(s.Work switch
        {
            KamertonConverterWork.Creating => "kamerton-converter-window-work-creating",
            KamertonConverterWork.Grinding => "kamerton-converter-window-work-grinding",
            KamertonConverterWork.Printing => "kamerton-converter-window-work-printing",
            _ => "kamerton-converter-window-work-idle",
        });

        var loaded = s.Bluespace + s.Redspace;
        CrystalBar.Value = s.MaxCrystals > 0 ? (float) loaded / s.MaxCrystals : 0f;
        CrystalLabel.Text = Loc.GetString("kamerton-converter-window-crystal-count",
            ("bluespace", s.Bluespace), ("redspace", s.Redspace), ("max", s.MaxCrystals));
        StableLabel.Text = N(s.StableEnergy);
        UnstableLabel.Text = N(s.UnstableEnergy);
        PowerBar.Value = s.MaxPower > 0 ? s.Power / s.MaxPower : 0f;
        PowerLabel.Text = $"{N(s.Power)} / {N(s.MaxPower)}";
        MaterialsLabel.Text = Loc.GetString("kamerton-converter-window-materials-value",
            ("plasma", s.Plasma), ("uranium", s.Uranium), ("cost", s.SheetCost));
        CellLabel.Text = s.CellName == null
            ? Loc.GetString("kamerton-converter-window-cell-none")
            : Loc.GetString(s.CellCharged ? "kamerton-converter-window-cell-charged" : "kamerton-converter-window-cell-empty",
                ("name", s.CellName));

        var idle = s.Work == KamertonConverterWork.Idle;
        StartButton.Disabled = !idle || (create ? s.Bluespace < s.MaxCrystals || s.Power < s.CreatePower : loaded == 0);

        // Charging needs an empty cell and enough energy of the matching kind.
        var energy = s.CellStable ? s.StableEnergy : s.UnstableEnergy;
        var canCharge = s.CellName != null && !s.CellCharged && energy >= s.ChargeCost;
        ChargeButton.Disabled = !canCharge;
        PrintButton.Disabled = !idle || s.Power < s.PrintPower || s.Plasma < s.SheetCost || s.Uranium < s.SheetCost;
        EjectButton.Disabled = !idle;

        HintLabel.Text = s.CellName != null && !s.CellCharged && energy < s.ChargeCost
            ? Loc.GetString(s.CellStable ? "kamerton-converter-not-enough-stable" : "kamerton-converter-not-enough-unstable",
                ("need", s.ChargeCost), ("have", MathF.Floor(energy)))
            : string.Empty;
    }
}

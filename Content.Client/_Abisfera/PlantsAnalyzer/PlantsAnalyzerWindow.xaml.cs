using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Abisfera.PlantsAnalyzer;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Utility;
using Content.Shared.IdentityManagement;

namespace Content.Client._Abisfera.PlantsAnalyzer
{
    public sealed class PlantsAnalyzerWindow : FancyWindow
    {
        private readonly IEntityManager _entityManager;

        // Объявляем все элементы управления, которые были в XAML
        private readonly Label _noPlantDataText;
        private readonly BoxContainer _plantDataContainer;
        private readonly SpriteView _spriteView;
        private readonly TextureRect _noDataTex;
        private readonly RichTextLabel _nameLabel;
        private readonly Label _speciesLabel;
        private readonly Label _scanModeLabel;
        private readonly Label _deadLabel;
        private readonly Label _optimalConditionsLabel;
        private readonly Label _potencyLevelLabel;
        private readonly Label _productionLevelLabel;
        private readonly Label _pestLevelLabel;
        private readonly Label _weedLevelLabel;
        private readonly Label _toxinsLabel;
        private readonly Label _ageLabel;
        private readonly Label _healthLabel;
        private readonly Label _mutationLevelLabel;
        private readonly Label _mutationsLabel;
        private readonly Label _chemicalsLabel;
        private readonly Label _chemicalsLabelWithLineBreaks;
        private readonly PanelContainer _alertsDivider;
        private readonly BoxContainer _alertsContainer;

        public PlantsAnalyzerWindow()
        {
            _entityManager = IoCManager.Resolve<IEntityManager>();

            Title = "Plants Analyzer";
            MinWidth = 300;
            MaxHeight = 525;

            var scroll = new ScrollContainer
            {
                Margin = new Thickness(5),
                ReturnMeasure = true,
                VerticalExpand = true
            };
            AddChild(scroll);

            var rootContainer = new BoxContainer
            {
                Name = "RootContainer",
                VerticalExpand = true,
                Orientation = BoxContainer.LayoutOrientation.Vertical
            };
            scroll.AddChild(rootContainer);

            _noPlantDataText = new Label { Name = "NoPlantDataText", Text = Loc.GetString("plants-analyzer-window-no-plant-data-text") };
            rootContainer.AddChild(_noPlantDataText);

            _plantDataContainer = new BoxContainer { Name = "PlantDataContainer", Margin = new Thickness(0, 0, 0, 5), Orientation = BoxContainer.LayoutOrientation.Vertical };
            rootContainer.AddChild(_plantDataContainer);

            var headerContainer = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 0, 0, 5) };
            _plantDataContainer.AddChild(headerContainer);

            _spriteView = new SpriteView { OverrideDirection = Direction.South, Scale = new Vector2(2, 2), Name = "SpriteView", SetSize = new Vector2(64, 64) };
            headerContainer.AddChild(_spriteView);

            _noDataTex = new TextureRect { Name = "NoDataTex", SetSize = new Vector2(64, 64), Visible = false, Stretch = TextureRect.StretchMode.KeepAspectCentered, TexturePath = "/Textures/Interface/Misc/health_analyzer_out_of_range.png" };
            headerContainer.AddChild(_noDataTex);

            var nameContainer = new BoxContainer { Margin = new Thickness(5, 0, 0, 0), Orientation = BoxContainer.LayoutOrientation.Vertical, VerticalAlignment = VAlignment.Top };
            headerContainer.AddChild(nameContainer);

            _nameLabel = new RichTextLabel { Name = "NameLabel", SetWidth = 150 };
            nameContainer.AddChild(_nameLabel);

            _speciesLabel = new Label { Name = "SpeciesLabel", VerticalAlignment = VAlignment.Top, StyleClasses = { "LabelSubText" } };
            nameContainer.AddChild(_speciesLabel);

            _scanModeLabel = new Label { Margin = new Thickness(0, 0, 5, 0), HorizontalExpand = true, HorizontalAlignment = HAlignment.Right, VerticalExpand = true, VerticalAlignment = VAlignment.Top, Name = "ScanModeLabel", Text = Loc.GetString("plants-analyzer-window-entity-unknown-text") };
            headerContainer.AddChild(_scanModeLabel);

            _deadLabel = new Label { Name = "DeadLabel", Visible = false, Text = Loc.GetString("plants-analyzer-window-plant-dead") };
            _plantDataContainer.AddChild(_deadLabel);

            _optimalConditionsLabel = new Label { Name = "OptimalConditionsLabel", Visible = false };
            _plantDataContainer.AddChild(_optimalConditionsLabel);

            _plantDataContainer.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });

            var grid = new GridContainer { Margin = new Thickness(0, 5, 0, 0), Columns = 2 };
            _plantDataContainer.AddChild(grid);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-potency-level-text") });
            _potencyLevelLabel = new Label { Name = "PotencyLevelLabel" };
            grid.AddChild(_potencyLevelLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-production-level-text") });
            _productionLevelLabel = new Label { Name = "ProductionLevelLabel" };
            grid.AddChild(_productionLevelLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-pest-level-text") });
            _pestLevelLabel = new Label { Name = "PestLevelLabel" };
            grid.AddChild(_pestLevelLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-weed-level-text") });
            _weedLevelLabel = new Label { Name = "WeedLevelLabel" };
            grid.AddChild(_weedLevelLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-toxins-text") });
            _toxinsLabel = new Label { Name = "ToxinsLabel" };
            grid.AddChild(_toxinsLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-age-text") });
            _ageLabel = new Label { Name = "AgeLabel" };
            grid.AddChild(_ageLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-health-text") });
            _healthLabel = new Label { Name = "HealthLabel" };
            grid.AddChild(_healthLabel);

            grid.AddChild(new Label { Text = Loc.GetString("plants-analyzer-window-mutation-level-text") });
            _mutationLevelLabel = new Label { Name = "MutationLevelLabel" };
            grid.AddChild(_mutationLevelLabel);

            _mutationsLabel = new Label { Name = "MutationsLabel" };
            _plantDataContainer.AddChild(_mutationsLabel);

            _chemicalsLabel = new Label { Name = "ChemicalsLabel" };
            _plantDataContainer.AddChild(_chemicalsLabel);

            _chemicalsLabelWithLineBreaks = new Label { Name = "ChemicalsLabelWithLineBreaks", Text = "" };
            _plantDataContainer.AddChild(_chemicalsLabelWithLineBreaks);

            _alertsDivider = new PanelContainer { Name = "AlertsDivider", Visible = false, StyleClasses = { "LowDivider" } };
            rootContainer.AddChild(_alertsDivider);

            _alertsContainer = new BoxContainer { Name = "AlertsContainer", Visible = false, Margin = new Thickness(0, 5, 0, 5), Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalAlignment = HAlignment.Center };
            rootContainer.AddChild(_alertsContainer);
        }

        public void Populate(PlantsAnalyzerScannedUserMessage msg)
        {
            var target = _entityManager.GetEntity(msg.TargetEntity);

            if (target == null)
            {
                _noPlantDataText.Visible = true;
                return;
            }

            _noPlantDataText.Visible = false;

            _scanModeLabel.Text = msg.ScanMode
                ? Loc.GetString("plants-analyzer-window-scan-mode-active")
                : Loc.GetString("plants-analyzer-window-scan-mode-inactive");
            _scanModeLabel.FontColorOverride = msg.ScanMode ? Color.Green : Color.Red;

            _spriteView.SetEntity(target.Value);
            _spriteView.Visible = msg.ScanMode;
            _noDataTex.Visible = !msg.ScanMode;

            var name = new FormattedMessage();
            name.PushColor(Color.White);
            name.AddText(Identity.Name(target.Value, _entityManager));
            _nameLabel.SetMessage(name);

            _speciesLabel.Text = msg.PlantName;

            _potencyLevelLabel.Text = $"{msg.PotencyLevel:F1}";
            _productionLevelLabel.Text = $"{msg.ProductionLevel:F1} un";
            _pestLevelLabel.Text = $"{msg.PestLevel * 10:F1} %";
            _weedLevelLabel.Text = $"{msg.WeedLevel * 10:F1} %";
            _toxinsLabel.Text = $"{msg.Toxins * 10:F1} %";
            _ageLabel.Text = $"{msg.Age}";
            _healthLabel.Text = $"{msg.Health:F1}";
            _mutationLevelLabel.Text = $"{msg.MutationLevel:F1}";

            _deadLabel.Visible = msg.IsDead;
            _deadLabel.Text = Loc.GetString("plants-analyzer-window-plant-dead");

            _mutationsLabel.Text = $"{Loc.GetString("plants-analyzer-window-mutations")} {msg.Mutations}";
            var chemicals = msg.Chemicals;
            if (chemicals?.Any() == true)
            {
                _chemicalsLabelWithLineBreaks.Text = $"{Loc.GetString("plants-analyzer-window-chemicals")} {chemicals}";
            }
            else
            {
                _chemicalsLabelWithLineBreaks.Text = Loc.GetString("plants-analyzer-window-no-chemicals");
            }

            var showAlerts = !string.IsNullOrEmpty(msg.OptimalConditions) || msg.HasKudzu;

            _alertsDivider.Visible = showAlerts;
            _alertsContainer.Visible = showAlerts;

            if (showAlerts)
            {
                _alertsContainer.DisposeAllChildren();

                if (msg.HasKudzu == true)
                {
                    var kudzuAlertContainer = new BoxContainer
                    {
                        Orientation = BoxContainer.LayoutOrientation.Vertical,
                        HorizontalAlignment = HAlignment.Center,
                        VerticalAlignment = VAlignment.Center,
                        Margin = new Thickness(0, 4),
                    };

                    var kudzuIcon = new TextureRect
                    {
                        TexturePath = "/Textures/Objects/Devices/health_analyzer.rsi/toxin.png",
                        SetSize = new Vector2(15, 15),
                        HorizontalAlignment = HAlignment.Center,
                        VerticalAlignment = VAlignment.Center,
                        Margin = new Thickness(0, 0, 0, 10),
                    };

                    kudzuAlertContainer.AddChild(kudzuIcon);

                    var kudzuTextLabel = new RichTextLabel
                    {
                        Margin = new Thickness(0,10, 0, 0),
                        MaxWidth = 400,
                    };

                    kudzuTextLabel.SetMessage(Loc.GetString("plants-analyzer-window-kudzu-warning"), defaultColor: Color.Red);

                    kudzuAlertContainer.AddChild(kudzuTextLabel);

                    _alertsContainer.AddChild(kudzuAlertContainer);

                    _alertsContainer.AddChild(new PanelContainer
                    {
                        StyleClasses = { "LowDivider" },
                        Visible = true
                    });
                }

                if (!string.IsNullOrEmpty(msg.OptimalConditions))
                {
                    var optimalConditionsContainer = new BoxContainer
                    {
                        Orientation = BoxContainer.LayoutOrientation.Horizontal,
                        HorizontalAlignment = HAlignment.Center,
                        VerticalAlignment = VAlignment.Center,
                        Margin = new Thickness(0, 4),
                    };

                    var optimalConditionsIcon = new TextureRect
                    {
                        HorizontalAlignment = HAlignment.Center,
                        VerticalAlignment = VAlignment.Center,
                    };

                    optimalConditionsContainer.AddChild(optimalConditionsIcon);

                    var optimalConditionsLabel = new RichTextLabel
                    {
                        Margin = new Thickness(5, 0, 0, 0),
                        MaxWidth = 400,
                    };

                    optimalConditionsLabel.SetMessage(msg.OptimalConditions, defaultColor: Color.Yellow);

                    optimalConditionsContainer.AddChild(optimalConditionsLabel);

                    _alertsContainer.AddChild(optimalConditionsContainer);

                    _alertsContainer.AddChild(new PanelContainer
                    {
                        StyleClasses = { "LowDivider" },
                        Visible = true
                    });
                }
            }
        }
    }
}